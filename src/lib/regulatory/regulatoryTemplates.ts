export function calculateRegulatoryValues(templateId: string, values: Record<string, unknown>) {
  const result: Record<string, number> = {};
  const num = (key: string, suffix = '') => {
    const value = values[`${key}${suffix}`] ?? (suffix ? undefined : values[key]);
    return typeof value === 'number' && Number.isFinite(value) ? value : Number(value ?? 0) || 0;
  };

  if (templateId === 'RCO_FORM_A_CPP_OPEN_ACCESS') {
    const gross = num('grossTotalElectricity');
    const target = gross * num('rcoNotifiedPercent') / 100;
    const compliance = num('grossNonFossilConsumption') + num('recsEnergy');
    const surplus = compliance - target;
    result.rcoTarget = target;
    result.rcoCompliance = compliance;
    result.rcoCompliancePercent = gross > 0 ? compliance / gross * 100 : 0;
    result.rcoSurplusDeficit = surplus;
    result.rcoSurplusDeficitPercent = gross > 0 ? surplus / gross * 100 : 0;
  }

  if (templateId.startsWith('CCTS_')) {
    for (const suffix of ['', '__BASELINE', '__ASSESSMENT']) {
      const direct = num('solidFuelEnergyEmission', suffix) + num('solidFuelProcessEmission', suffix)
        + num('liquidFuelEnergyEmission', suffix) + num('liquidFuelProcessEmission', suffix)
        + num('gaseousFuelEnergyEmission', suffix) + num('gaseousFuelProcessEmission', suffix)
        + num('calcinationEmission', suffix) - num('unburntCoalAdjustment', suffix)
        - num('steamExportAdjustment', suffix) - num('chilledWaterExportAdjustment', suffix);
      const indirect = num('outsideElectricityEmission', suffix) - num('electricityExportAdjustment', suffix)
        + num('steamImportAdjustment', suffix) + num('chilledWaterImportAdjustment', suffix)
        + num('intermediaryImportAdjustment', suffix);
      result[`totalScope1${suffix}`] = direct;
      result[`totalScope2${suffix}`] = indirect;
      result[`totalScope1Scope2${suffix}`] = direct + indirect;
      const production = num('ghgEquivalentProduction', suffix) || num('totalEquivalentProduct', suffix)
        || num('equivalentPaperProduction', suffix);
      result[`emissionIntensity${suffix}`] = production > 0 ? (direct + indirect) / production : 0;
      const generation = num('dgGeneration', suffix) + num('gasGeneratorGeneration', suffix) + num('steamTurbineGeneration', suffix)
        + num('gasTurbineGeneration', suffix) + num('cogenBackPressure', suffix)
        + num('cogenCondensing', suffix) + num('whrGeneration', suffix)
        + num('renewableInPlant', suffix) + num('cppDedicatedLine', suffix)
        + num('outsideCppWheeling', suffix) + num('renewableDedicatedLine', suffix)
        + num('renewableGridWheeling', suffix) + num('gridImported', suffix)
        - num('electricityExport', suffix);
      result[`totalElectricityAvailability${suffix}`] = generation;

      // Textile summary sheets show D5/D6 energy, normalization factors,
      // normalized SEC and REC-adjusted SEC. The formulas below follow the
      // formulas printed on the supplied SG1/SG2/SG3/SG4 summary sheets.
      const intermediary = num('intermediaryEnergy', suffix);
      const plantEnergyToe = (num('thermalElectricalEnergy', suffix) + intermediary) / 10;
      const totalProduct = num('totalEquivalentProduct', suffix);
      const gateToGateEnergy = num('thermalElectricalEnergy', suffix) + intermediary
        - num('nfPowerMix', suffix) - num('nfCppPlf', suffix)
        - num('nfFuelQuality', suffix) - num('nfOther', suffix)
        - num('nfStartStop', suffix);
      const normalizedSec = totalProduct > 0 ? (gateToGateEnergy / 10) / totalProduct : 0;
      const energyAfterRec = num('recCompliance', suffix) + gateToGateEnergy / 10;
      result[`plantEnergyToe${suffix}`] = plantEnergyToe;
      result[`gtgSecWithoutNormalization${suffix}`] = totalProduct > 0 ? plantEnergyToe / totalProduct : 0;
      result[`gateToGateEnergy${suffix}`] = gateToGateEnergy;
      result[`normalizedGtgSec${suffix}`] = normalizedSec;
      result[`energyAfterRec${suffix}`] = energyAfterRec;
      const baselineNormalization = num('baselineNormalization', '__BASELINE') || num('baselineNormalization');
      result[`normalizedSecAfterRec${suffix}`] = totalProduct > 0
        ? energyAfterRec / totalProduct - baselineNormalization
        : 0;
    }
  }
  return result;
}
