export type RegulatoryFramework = 'RCO' | 'RPO' | 'PAT' | 'CCTS';
export type RegulatoryColumn = 'BASELINE' | 'ASSESSMENT' | 'TARGET' | 'NOT_APPLICABLE' | 'VALUE';

export interface RegulatoryField {
  key: string;
  label: string;
  unit: string;
  sourceRef?: string;
  columns: RegulatoryColumn[];
  input?: boolean;
  required?: boolean;
  calculationNote?: string;
  kind?: 'number' | 'text' | 'date';
}

export interface RegulatorySection {
  id: string;
  title: string;
  description?: string;
  fields: RegulatoryField[];
}

export interface RegulatoryTemplate {
  id: string;
  framework: RegulatoryFramework;
  title: string;
  sector: string;
  formName: string;
  sections: RegulatorySection[];
}

const f = (
  key: string, label: string, unit: string,
  sourceRef = '', columns: RegulatoryColumn[] = ['BASELINE', 'ASSESSMENT'],
  extra: Partial<RegulatoryField> = {}
): RegulatoryField => ({ key, label, unit, sourceRef, columns, input: true, ...extra });

